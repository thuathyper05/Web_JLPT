export const hasRealKanji = (str) => Boolean(str && /[\u4E00-\u9FAF\u3400-\u4DBF]/.test(String(str)));
export const hasKatakana = (str) => Boolean(str && /[\u30A0-\u30FF]/.test(String(str)));

/**
 * Pure 1-to-1 Unicode Hiragana to Katakana converter
 * Matches Hiragana characters (U+3041 to U+3096) and converts to Katakana (U+30A1 to U+30F6)
 */
export const hiraganaToKatakana = (str) => {
  if (!str) return '';
  return String(str).replace(/[\u3041-\u3096]/g, (ch) =>
    String.fromCharCode(ch.charCodeAt(0) + 0x60)
  );
};

// Set of all distinct Katakana loanwords in JLPT N5 curriculum
export const KATAKANA_WORDS_SET = new Set(
  Object.values(KATAKANA_LOANWORDS_MAP).filter((v) => hasKatakana(v))
);

// Reverse Hiragana lookup dictionary for ultra-fast matching
export const HIRAGANA_TO_KATAKANA_MAP = {};
Object.values(KATAKANA_LOANWORDS_MAP).forEach((val) => {
  if (hasKatakana(val)) {
    // Generate hiragana counterpart
    const hira = String(val).replace(/[\u30A1-\u30F6]/g, (ch) =>
      String.fromCharCode(ch.charCodeAt(0) - 0x60)
    );
    HIRAGANA_TO_KATAKANA_MAP[hira] = val;
  }
});

/**
 * Determine whether a vocabulary or question is a Katakana loanword
 */
export const isKatakanaLoanword = (item) => {
  if (!item || typeof item !== 'object') return false;
  const rawKanji = item.kanji ? String(item.kanji).trim() : '';
  const realKanji = hasRealKanji(rawKanji);
  if (!realKanji && hasKatakana(rawKanji)) return true;

  const rawKana = String(item.clean_kana || item.kana || '').trim();
  if (hasKatakana(rawKana)) return true;

  const hiraForm = rawKana;
  if (HIRAGANA_TO_KATAKANA_MAP[hiraForm]) return true;

  const kataConverted = hiraganaToKatakana(hiraForm);
  if (KATAKANA_WORDS_SET.has(kataConverted)) return true;

  const romajiKey = item.romaji ? String(item.romaji).toLowerCase().replace(/[^a-z]/g, '') : '';
  const viKey = item.vietnamese ? String(item.vietnamese).toLowerCase().trim() : '';
  const viCleanKey = item.clean_vietnamese ? String(item.clean_vietnamese).toLowerCase().trim() : '';

  return Boolean(
    KATAKANA_LOANWORDS_MAP[romajiKey] ||
    KATAKANA_LOANWORDS_MAP[viKey] ||
    KATAKANA_LOANWORDS_MAP[viCleanKey]
  );
};

/**
 * Clean redundant '(hiragana)' reading annotations from Katakana strings
 * Ví dụ: 'コンピューター (こんぴゅーたー)' thành 'コンピューター'
 * Ví dụ: 'アクセサリー (あくせさりー)' thành 'アクセサリー'
 * Giữ nguyên Kanji có Furigana: '学校 (がっこう)'
 */
export const cleanKatakanaDisplay = (str) => {
  if (!str || typeof str !== 'string') return str;
  let text = str.trim();

  // If starts with Katakana followed by reading in parentheses, strip the reading
  const kataWithReadingMatch = text.match(/^([\u30A0-\u30FF\s\u30FC]+)\s*\([^)]+\)$/);
  if (kataWithReadingMatch) {
    text = kataWithReadingMatch[1].trim();
  }

  // If text has no Kanji, check if it's a loanword stored in Hiragana
  if (!hasRealKanji(text)) {
    if (HIRAGANA_TO_KATAKANA_MAP[text]) {
      return HIRAGANA_TO_KATAKANA_MAP[text];
    }
    const kataForm = hiraganaToKatakana(text);
    if (KATAKANA_WORDS_SET.has(kataForm)) {
      return kataForm;
    }
  }

  return text;
};

/**
 * Retrieve the canonical Kana representation:
 * For Katakana loanwords, ALWAYS returns pure Katakana.
 * For Kanji words or native Hiragana, returns clean Hiragana.
 */
export const getEffectiveKana = (item) => {
  if (!item) return '';
  if (typeof item === 'string') return cleanKatakanaDisplay(item);

  const rawKanji = item.kanji ? String(item.kanji).trim() : '';
  const realKanji = hasRealKanji(rawKanji);
  if (!realKanji && hasKatakana(rawKanji)) {
    return rawKanji;
  }

  const rawKana = String(item.clean_kana || item.kana || '').trim();
  if (hasKatakana(rawKana)) {
    return cleanKatakanaDisplay(rawKana);
  }

  if (HIRAGANA_TO_KATAKANA_MAP[rawKana]) {
    return HIRAGANA_TO_KATAKANA_MAP[rawKana];
  }

  const kataFromHira = hiraganaToKatakana(rawKana);
  if (KATAKANA_WORDS_SET.has(kataFromHira)) {
    return kataFromHira;
  }

  const romajiKey = item.romaji ? String(item.romaji).toLowerCase().replace(/[^a-z]/g, '') : '';
  const viKey = item.vietnamese ? String(item.vietnamese).toLowerCase().trim() : '';
  const viCleanKey = item.clean_vietnamese ? String(item.clean_vietnamese).toLowerCase().trim() : '';

  const dictMatch =
    KATAKANA_LOANWORDS_MAP[romajiKey] ||
    KATAKANA_LOANWORDS_MAP[viKey] ||
    KATAKANA_LOANWORDS_MAP[viCleanKey];

  if (dictMatch && hasKatakana(dictMatch)) {
    return dictMatch;
  }

  return rawKana;
};

/**
 * Retrieve the canonical primary Japanese word for display:
 * - Nếu có chữ Hán: trả về Kanji (ví dụ: '先生', '日本')
 * - Nếu là Katakana: trả về Katakana (ví dụ: 'スプーン', 'テレビ')
 * - Khác: trả về Hiragana (ví dụ: 'わたし', 'これ')
 */
export const getEffectiveJapaneseWord = (item) => {
  if (!item) return '';
  if (typeof item === 'string') return cleanKatakanaDisplay(item);
  if (item.kanji && hasRealKanji(item.kanji)) {
    return String(item.kanji).trim();
  }
  return getEffectiveKana(item);
};

/**
 * Standardize any vocabulary record so Katakana loanwords are never displayed as Kanji or Hiragana
 */
export const normalizeVocabularyItem = (item) => {
  if (!item || typeof item !== 'object') return item;
  const clone = { ...item };

  const rawKanji = clone.kanji ? String(clone.kanji).trim() : '';
  const realKanji = hasRealKanji(rawKanji);
  const kanjiIsKata = hasKatakana(rawKanji);

  // 1. If kanji contains Katakana without real Kanji (e.g. "スプーン" in kanji column)
  if (!realKanji && kanjiIsKata) {
    clone.kana = rawKanji;
    clone.clean_kana = rawKanji;
    clone.display_kana = rawKanji;
    clone.kanji = null;
  } else if (!realKanji) {
    clone.kanji = null;
  }

  // 2. Cross-reference dictionary by romaji or vietnamese to restore Katakana loanwords
  const romajiKey = clone.romaji ? String(clone.romaji).toLowerCase().replace(/[^a-z]/g, '') : '';
  const viKey = clone.vietnamese ? String(clone.vietnamese).toLowerCase().trim() : '';
  const viCleanKey = clone.clean_vietnamese ? String(clone.clean_vietnamese).toLowerCase().trim() : '';
  const rawKana = String(clone.clean_kana || clone.kana || '').trim();

  let dictMatch =
    (HIRAGANA_TO_KATAKANA_MAP[rawKana]) ||
    (KATAKANA_WORDS_SET.has(hiraganaToKatakana(rawKana)) ? hiraganaToKatakana(rawKana) : null) ||
    KATAKANA_LOANWORDS_MAP[romajiKey] ||
    KATAKANA_LOANWORDS_MAP[viKey] ||
    KATAKANA_LOANWORDS_MAP[viCleanKey];

  if (dictMatch && !hasRealKanji(clone.kanji)) {
    clone.kana = dictMatch;
    clone.clean_kana = dictMatch;
    clone.display_kana = dictMatch;
    clone.kanji = null;
    clone.is_katakana = true;
  }

  // 3. Ensure clean_kana and kana consistency
  if (clone.clean_kana && hasKatakana(clone.clean_kana)) {
    clone.clean_kana = cleanKatakanaDisplay(clone.clean_kana);
    clone.kana = clone.clean_kana;
    clone.display_kana = clone.clean_kana;
  } else if (clone.kana && hasKatakana(clone.kana)) {
    clone.kana = cleanKatakanaDisplay(clone.kana);
    clone.clean_kana = clone.kana;
    clone.display_kana = clone.kana;
  }

  return clone;
};

/**
 * Standardize quiz questions:
 * - Eliminates '(hiragana)' attached to Katakana words in questions and options
 * - Converts any Hiragana loanwords back to pure Katakana
 * - Eliminates 'kanji_to_reading' questions for Katakana words (converts them to jp_to_vi)
 */
export const normalizeQuizQuestion = (q) => {
  if (!q || typeof q !== 'object') return q;
  const clone = normalizeVocabularyItem(q);

  const isTargetKata = isKatakanaLoanword(clone) || hasKatakana(clone.clean_kana || clone.kana);

  // If question was incorrectly generated as kanji_to_reading for a Katakana loanword
  if (clone.type === 'kanji_to_reading' && (!hasRealKanji(clone.kanji) || isTargetKata)) {
    const targetKata = getEffectiveKana(clone) || clone.clean_kana || clone.kana;
    clone.type = 'vi_to_jp';
    clone.prompt = 'Chọn từ Katakana chính xác';
    clone.question = clone.clean_vietnamese || clone.vietnamese || clone.question;
    clone.correct_answer = targetKata;
    const pool = [
      'ノート', 'カード', 'ボールペン', 'シャープペンシル', 'テレビ',
      'ラジオ', 'カメラ', 'コンピューター', 'コーヒー', 'スプーン',
      'ナイフ', 'フォーク', 'パソコン', 'パン', 'ジュース', 'ネクタイ',
      'ワイン', 'エレベーター', 'スーパー', 'タクシー'
    ].filter(w => w !== targetKata);
    const d1 = pool[Math.floor(Math.random() * pool.length)];
    const pool2 = pool.filter(w => w !== d1);
    const d2 = pool2[Math.floor(Math.random() * pool2.length)];
    const pool3 = pool2.filter(w => w !== d2);
    const d3 = pool3[Math.floor(Math.random() * pool3.length)];
    const opts = [targetKata, d1, d2, d3];
    for (let i = opts.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [opts[i], opts[j]] = [opts[j], opts[i]];
    }
    clone.options = opts;
  }

  // Clean question text
  if (clone.question) {
    clone.question = cleanKatakanaDisplay(clone.question);
  }

  // Clean correct answer
  if (clone.correct_answer) {
    clone.correct_answer = cleanKatakanaDisplay(clone.correct_answer);
  }

  // Clean options array
  if (Array.isArray(clone.options)) {
    clone.options = clone.options.map(opt => cleanKatakanaDisplay(opt));
  }

  return clone;
};

/**
 * Deep-traverse and normalize arrays, objects, or quiz responses
 */
export const normalizeVocabCollection = (data) => {
  if (!data) return data;
  if (Array.isArray(data)) {
    return data.map(normalizeVocabularyItem);
  }
  if (typeof data === 'object') {
    const copy = { ...data };
    if (Array.isArray(copy.vocabularies)) {
      copy.vocabularies = copy.vocabularies.map(normalizeVocabularyItem);
    }
    if (Array.isArray(copy.questions)) {
      copy.questions = copy.questions.map(normalizeQuizQuestion);
    }
    if (Array.isArray(copy.garden)) {
      copy.garden = copy.garden.map(normalizeVocabularyItem);
    }
    if (Array.isArray(copy.due)) {
      copy.due = copy.due.map(normalizeVocabularyItem);
    }
    if (copy.vocabulary) {
      copy.vocabulary = normalizeVocabularyItem(copy.vocabulary);
    }
    return copy;
  }
  return data;
};
