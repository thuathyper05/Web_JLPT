export const hasRealKanji = (str) => Boolean(str && /[\u4E00-\u9FAF\u3400-\u4DBF]/.test(String(str)));
export const hasKatakana = (str) => Boolean(str && /[\u30A0-\u30FF]/.test(String(str)));

/**
 * Standardize any vocabulary record so Katakana loanwords are never displayed as Kanji or Hiragana
 */
export const normalizeVocabularyItem = (item) => {
  if (!item || typeof item !== 'object') return item;
  const clone = { ...item };

  const rawKanji = clone.kanji ? String(clone.kanji).trim() : '';
  const realKanji = hasRealKanji(rawKanji);
  const kanjiIsKata = hasKatakana(rawKanji);

  // 1. If kanji contains Katakana without real Kanji (e.g. "スプーン" in kanji column)
  if (!realKanji && kanjiIsKata) {
    clone.kana = rawKanji;
    clone.clean_kana = rawKanji;
    clone.kanji = null;
  } else if (!realKanji) {
    clone.kanji = null;
  }

  // 2. Cross-reference dictionary by romaji or vietnamese to restore Katakana loanwords
  const romajiKey = clone.romaji ? String(clone.romaji).toLowerCase().replace(/[^a-z]/g, '') : '';
  const viKey = clone.vietnamese ? String(clone.vietnamese).toLowerCase().trim() : '';
  const viCleanKey = clone.clean_vietnamese ? String(clone.clean_vietnamese).toLowerCase().trim() : '';

  const dictMatch = KATAKANA_LOANWORDS_MAP[romajiKey] || KATAKANA_LOANWORDS_MAP[viKey] || KATAKANA_LOANWORDS_MAP[viCleanKey];
  if (dictMatch && !hasRealKanji(clone.kanji)) {
    clone.kana = dictMatch;
    clone.clean_kana = dictMatch;
    clone.kanji = null;
  }

  // 3. Ensure clean_kana and kana consistency
  if (clone.clean_kana && hasKatakana(clone.clean_kana)) {
    clone.kana = clone.clean_kana;
  } else if (clone.kana && hasKatakana(clone.kana)) {
    clone.clean_kana = clone.kana;
  }

  return clone;
};

/**
 * Deep-traverse and normalize arrays, objects, or quiz responses
 */
export const normalizeVocabCollection = (data) => {
  if (!data) return data;
  if (Array.isArray(data)) {
    return data.map(normalizeVocabularyItem);
  }
  if (typeof data === 'object') {
    const copy = { ...data };
    if (Array.isArray(copy.vocabularies)) {
      copy.vocabularies = copy.vocabularies.map(normalizeVocabularyItem);
    }
    if (Array.isArray(copy.questions)) {
      copy.questions = copy.questions.map(q => {
        const normQ = normalizeVocabularyItem(q);
        if (hasKatakana(normQ.clean_kana || normQ.kana)) {
          normQ.clean_kana = normQ.clean_kana || normQ.kana;
          normQ.kana = normQ.clean_kana;
        }
        return normQ;
      });
    }
    if (Array.isArray(copy.garden)) {
      copy.garden = copy.garden.map(normalizeVocabularyItem);
    }
    if (Array.isArray(copy.due)) {
      copy.due = copy.due.map(normalizeVocabularyItem);
    }
    if (copy.vocabulary) {
      copy.vocabulary = normalizeVocabularyItem(copy.vocabulary);
    }
    return copy;
  }
  return data;
};
